export interface BridePlanAnalysis {
  presetMode: 'compact' | 'balanced' | 'extended';
  activeTemplateItems: BrideChecklistTemplateItem[];
  completedTemplateCount: number;
  completionPercent: number;
  estimatedTemplateTotalEgp: number;
  completedEstimatedSpendEgp: number;
  remainingEstimatedSpendEgp: number;
  missingEssentialItems: BrideChecklistTemplateItem[];
  categoryCoverage: {
    categoryId: string;
    nameAr: string;
    nameEn: string;
    totalItems: number;
    checkedItems: number;
    estimatedBudgetEgp: number;
  }[];
}

export function analyzeBrideTrousseauPlan(input: {
  presetMode: 'compact' | 'balanced' | 'extended';
  checkedItemIds: string[];
  qtyOverrides?: Record<string, number>;
  customItems?: UserBrideCustomItem[];
  categories?: BrideCategoryGuide[];
  templateItems?: BrideChecklistTemplateItem[];
}): BridePlanAnalysis {
  const categories = input.categories || BRIDE_ENCYCLOPEDIA_CATEGORIES;
  const templates = input.templateItems || BRIDE_CHECKLIST_TEMPLATES;
  const qtyOverrides = input.qtyOverrides || {};
  const checkedSet = new Set(input.checkedItemIds);

  const activeTemplateItems = templates.filter((item) => item.presets.includes(input.presetMode));
  const customItems = input.customItems || [];

  let estimatedTemplateTotalEgp = 0;
  let completedEstimatedSpendEgp = 0;
  let completedTemplateCount = 0;

  for (const item of activeTemplateItems) {
    const qty = qtyOverrides[item.id] ?? item.recommendedQty;
    const cost = item.estimatedUnitPriceEgp * qty;
    estimatedTemplateTotalEgp += cost;
    if (checkedSet.has(item.id)) {
      completedTemplateCount += 1;
      completedEstimatedSpendEgp += cost;
    }
  }

  for (const custom of customItems) {
    const cost = custom.estimatedUnitPriceEgp * custom.qty;
    estimatedTemplateTotalEgp += cost;
    if (custom.checked) {
      completedEstimatedSpendEgp += cost;
    }
  }

  const totalCount = activeTemplateItems.length + customItems.length;
  const checkedCustomCount = customItems.filter((c) => c.checked).length;
  const completionPercent =
    totalCount > 0
      ? Math.round(((completedTemplateCount + checkedCustomCount) / totalCount) * 100)
      : 0;

  const missingEssentialItems = activeTemplateItems.filter(
    (item) => item.priority === 'essential' && !checkedSet.has(item.id),
  );

  const categoryCoverage = categories.map((cat) => {
    const inCat = activeTemplateItems.filter((item) => item.categoryId === cat.id);
    const customInCat = customItems.filter((c) => c.categoryId === cat.id);
    const checkedCount =
      inCat.filter((i) => checkedSet.has(i.id)).length +
      customInCat.filter((c) => c.checked).length;
    const catBudget =
      inCat.reduce(
        (sum, i) => sum + i.estimatedUnitPriceEgp * (qtyOverrides[i.id] ?? i.recommendedQty),
        0,
      ) + customInCat.reduce((sum, c) => sum + c.estimatedUnitPriceEgp * c.qty, 0);

    return {
      categoryId: cat.id,
      nameAr: cat.nameAr,
      nameEn: cat.nameEn,
      totalItems: inCat.length + customInCat.length,
      checkedItems: checkedCount,
      estimatedBudgetEgp: catBudget,
    };
  });

  return {
    presetMode: input.presetMode,
    activeTemplateItems,
    completedTemplateCount,
    completionPercent,
    estimatedTemplateTotalEgp,
    completedEstimatedSpendEgp,
    remainingEstimatedSpendEgp: Math.max(0, estimatedTemplateTotalEgp - completedEstimatedSpendEgp),
    missingEssentialItems,
    categoryCoverage,
  };
}

