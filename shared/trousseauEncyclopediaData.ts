export function calculateConfigurableGroomPackage(
  pkg: GroomConfigurablePackage,
  slotOverrides: Record<string, string> = {},
  excludedSlots: string[] = [],
): {
  totalEgp: number;
  targetBudgetEgp: number;
  varianceEgp: number;
  selectedCount: number;
  resolvedSlots: {
    slotKey: string;
    slotLabelAr: string;
    slotLabelEn: string;
    excluded: boolean;
    selectedOption: GroomConfigurablePackage['slots'][number]['options'][number];
  }[];
} {
  let totalEgp = 0;
  let selectedCount = 0;

  const resolvedSlots = pkg.slots.map((slot) => {
    const isExcluded = !slot.required && excludedSlots.includes(slot.slotKey);
    const chosenId = slotOverrides[slot.slotKey] || slot.defaultOptionId;
    const selectedOption =
      slot.options.find((opt) => opt.optionId === chosenId) || slot.options[0];
    if (!isExcluded) {
      totalEgp += selectedOption.priceEgp;
      selectedCount += 1;
    }
    return {
      slotKey: slot.slotKey,
      slotLabelAr: slot.slotLabelAr,
      slotLabelEn: slot.slotLabelEn,
      excluded: isExcluded,
      selectedOption,
    };
  });

  return {
    totalEgp,
    targetBudgetEgp: pkg.targetBudgetEgp,
    varianceEgp: pkg.targetBudgetEgp - totalEgp,
    selectedCount,
    resolvedSlots,
  };
}

